#!/usr/bin/env python3
"""Solve QR RS parity-check equations over GF(256) with known plaintext.

This is intentionally an erasure solver, not a Reed-Solomon decoder. Each
block solves H*c=0 for the selected unknown codeword bytes. Partial plaintext
bytes are solved as byte unknowns and checked against their known bit masks.
"""
from __future__ import annotations
from pathlib import Path as _Path
def _self_dir():
    return _Path(__file__).resolve().parent

import argparse
import itertools
import sys

import cv2
import numpy as np
from qrcode import constants

sys.path.insert(0, str(_self_dir()))
import qr_decode as qd
import rs_constraints_search as rs


def gf_tables():
    exp = np.zeros(510, dtype=np.uint16)
    log = np.full(256, -1, dtype=np.int16)
    x = 1
    for i in range(255):
        exp[i] = x
        log[x] = i
        x <<= 1
        if x & 0x100:
            x ^= 0x11D
    exp[255:] = exp[:255]
    mul = np.zeros((256, 256), dtype=np.uint8)
    for a in range(1, 256):
        for b in range(1, 256):
            mul[a, b] = exp[int(log[a]) + int(log[b])]
    return exp.astype(np.uint8), log, mul


EXP, LOG, MUL = gf_tables()


def parity_matrix(n: int, nsym: int) -> np.ndarray:
    # RSCodec(fcr=0,generator=2) checks roots alpha^0..alpha^(nsym-1).
    # A high-degree-first codeword c has syndrome S_r=sum_j c_j*alpha^(r*(n-1-j)).
    h = np.empty((nsym, n), dtype=np.uint8)
    for r in range(nsym):
        for j in range(n):
            h[r, j] = EXP[(r * (n - 1 - j)) % 255]
    return h


def syndrome(codeword: np.ndarray, h: np.ndarray) -> np.ndarray:
    out = np.zeros(h.shape[0], dtype=np.uint8)
    for j, value in enumerate(codeword):
        if value:
            out ^= MUL[int(value), h[:, j]]
    return out


def solve_delta(base: np.ndarray, unknown: list[int], h: np.ndarray):
    """Return unique byte corrections on unknown positions, or None if inconsistent."""
    m, e = h.shape[0], len(unknown)
    syn = syndrome(base, h)
    if not e:
        return np.zeros(0, dtype=np.uint8) if not syn.any() else None
    a = np.concatenate((h[:, unknown], syn[:, None]), axis=1).copy()
    pivots = []
    rank = 0
    for col in range(e):
        candidates = np.flatnonzero(a[rank:, col])
        if not len(candidates):
            return None
        pivot = rank + int(candidates[0])
        if pivot != rank:
            a[[rank, pivot]] = a[[pivot, rank]]
        value = int(a[rank, col])
        inv = int(EXP[255 - int(LOG[value])])
        a[rank, col:] = MUL[a[rank, col:], inv]
        factors = a[:, col].copy()
        factors[rank] = 0
        rows = np.flatnonzero(factors)
        if len(rows):
            a[rows, col:] ^= MUL[factors[rows, None], a[rank, col:][None, :]]
        pivots.append(rank)
        rank += 1
    # Remaining parity equations must also agree.
    if np.any((a[:, :e] == 0).all(axis=1) & (a[:, e] != 0)):
        return None
    return np.asarray([a[row, e] for row in pivots], dtype=np.uint8)


def verify_solver():
    # A deterministic RS(43,15) fixture generated by qrcode's encoder API.
    from reedsolo import RSCodec
    msg = bytes(range(15))
    code = np.frombuffer(RSCodec(28, fcr=0, prim=0x11D, generator=2,
                                  c_exp=8).encode(msg), dtype=np.uint8).copy()
    h = parity_matrix(43, 28)
    if syndrome(code, h).any():
        raise RuntimeError("parity-check roots disagree with QR RS encoder")
    corrupted = code.copy()
    unknown = [0, 3, 7, 11, 16, 22, 29, 35, 42]
    for i, pos in enumerate(unknown):
        corrupted[pos] ^= (0x31 + i)
    delta = solve_delta(corrupted, unknown, h)
    if delta is None:
        raise RuntimeError("synthetic erasure system unexpectedly inconsistent")
    corrected = corrupted.copy()
    corrected[unknown] ^= delta
    if not np.array_equal(corrected, code):
        raise RuntimeError("linear solve did not recover the synthetic codeword")
    print("GF256 parity-check self-check: RS(43,15), 9 erasures recovered", flush=True)


def payload_for(data: bytes, count: int):
    bits = "".join(f"{x:08b}" for x in data)
    if int(bits[:4], 2) != 4 or int(bits[4:12], 2) != count:
        return None
    payload = bytes(int(bits[i:i + 8], 2) for i in range(12, 12 + count * 8, 8))
    if not payload.startswith(b"FortID{") or not payload.endswith(b"}"):
        return None
    if not all(32 <= x <= 126 for x in payload):
        return None
    return payload


def data_order(specs):
    return [(b, j) for j in range(max(s.data_count for s in specs))
            for b, s in enumerate(specs) if j < s.data_count]


def local_constraints(count: int, specs):
    constraints = rs.make_constraints(count)
    out = [dict() for _ in specs]
    # QR assigns consecutive data codewords to RS blocks first. Only the
    # transmitted codeword stream is column-interleaved (block_layout handles
    # that separate mapping).
    start = 0
    for b, spec in enumerate(specs):
        for global_i, (bitmask, value) in constraints.items():
            if start <= global_i < start + spec.data_count:
                out[b][global_i - start] = (bitmask, value)
        start += spec.data_count
    return out


def symbol_rx(bits, mask: int, coords, specs, mapping):
    raw = np.asarray([bits[i] ^ int(qd.mask_bit(mask, *coords[i]))
                      for i in range(1376)], dtype=np.uint8)
    tx = [int("".join(map(str, raw[i:i + 8])), 2) for i in range(0, 1376, 8)]
    blocks = [np.zeros(s.total_count, dtype=np.uint8) for s in specs]
    tx_for_block = [[] for _ in specs]
    for ti, (b, j) in enumerate(mapping):
        blocks[b][j] = tx[ti]
        tx_for_block[b].append(ti)
    return blocks, tx_for_block


def solve_block(received, confidences, spec, known, h):
    nsym = spec.total_count - spec.data_count
    base = received.copy()
    forced_partial = []
    for j, (bitmask, value) in known.items():
        if bitmask == 0xFF:
            # Exact known plaintext is a fixed symbol, not an erasure.
            base[j] = value
        else:
            # Keep the unconstrained bits free; solve the whole byte, then check the mask.
            base[j] = value & bitmask
            forced_partial.append(j)
    forbidden = set(known)
    ranked = sorted((j for j in range(spec.total_count) if j not in forbidden),
                    key=lambda j: float(confidences[j]))
    start = max(0, int(np.ceil(0.30 * spec.total_count)) - len(forced_partial))
    for quota in range(start, nsym - len(forced_partial) + 1):
        erased = sorted(forced_partial + ranked[:quota])
        delta = solve_delta(base, erased, h)
        if delta is None:
            continue
        corrected = base.copy()
        if erased:
            corrected[erased] ^= delta
        data = bytes(corrected[:spec.data_count])
        if any((data[j] & bitmask) != (value & bitmask)
               for j, (bitmask, value) in known.items()):
            # Enlarging the erasure set preserves the same unique solution,
            # so later quotas cannot repair a failed plaintext constraint.
            return None, quota + len(forced_partial)
        return data, quota + len(forced_partial)
    return None, nsym


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--levels", default="H,Q,M,L")
    ap.add_argument("--masks", default="0,1,2,3,4,5,6,7")
    ap.add_argument("--counts", help="optional inclusive total-payload range low:high")
    ap.add_argument("--classifier", choices=("median", "pixel"), default="median")
    ap.add_argument("--pixel-model", default="pixel_likelihood.npz",
                    help="model file under solver_support when --classifier pixel")
    ap.add_argument("--rank", choices=("min", "mean", "sum"), default="min",
                    help="aggregate eight module confidences into one RS-byte ranking")
    ap.add_argument("--self-check", action="store_true")
    args = ap.parse_args()
    if args.self_check:
        verify_solver()
        return

    if args.classifier == "median":
        bits, module_conf = rs.read_modules(50, 54, 200, .6, method="median")
    else:
        model = np.load(str(_self_dir() / args.pixel_model))
        bits, module_conf = model["bits"], model["support"] * model["llr"]
    coords = qd.data_coords(qd.function_map())
    levels = [(constants.ERROR_CORRECT_H, "H"),
              (constants.ERROR_CORRECT_Q, "Q"),
              (constants.ERROR_CORRECT_M, "M"),
              (constants.ERROR_CORRECT_L, "L")]
    wanted = set(args.levels.split(","))
    masks = [int(x) for x in args.masks.split(",")]
    for ec, name in levels:
        if name not in wanted:
            continue
        specs, mapping = qd.block_layout(ec)
        capacity = sum(s.data_count for s in specs)
        lo, hi = (8, capacity - 2)
        if args.counts:
            lo, hi_arg = map(int, args.counts.split(":"))
            hi = min(hi, hi_arg)
        # Erasures are whole RS bytes; aggregate the eight module margins using
        # the selected statistic before ranking candidate bytes.
        confidence_chunks = [module_conf[i * 8:i * 8 + 8] for i in range(172)]
        if args.rank == "min":
            tx_conf = [float(np.min(v)) for v in confidence_chunks]
        elif args.rank == "mean":
            tx_conf = [float(np.mean(v)) for v in confidence_chunks]
        else:
            tx_conf = [float(np.sum(v)) for v in confidence_chunks]
        hs = [parity_matrix(s.total_count, s.total_count - s.data_count) for s in specs]
        print("LEVEL", name, "blocks", [(s.total_count, s.data_count,
                                        s.total_count - s.data_count) for s in specs], flush=True)
        for mask in masks:
            received, tx_for_block = symbol_rx(bits, mask, coords, specs, mapping)
            # Map transmitted-byte confidence order into each deinterleaved block.
            block_conf = [np.zeros(s.total_count, dtype=np.float32) for s in specs]
            for ti, (b, j) in enumerate(mapping):
                block_conf[b][j] = tx_conf[ti]
            tried_counts = 0
            for count in range(lo, hi + 1):
                local = local_constraints(count, specs)
                blocks = []
                erasure_n = []
                for b, spec in enumerate(specs):
                    data, neras = solve_block(received[b], block_conf[b], spec,
                                              local[b], hs[b])
                    if data is None:
                        blocks = []
                        break
                    blocks.append(data)
                    erasure_n.append(neras)
                if len(blocks) != len(specs):
                    continue
                decoded_data = b"".join(blocks)
                payload = payload_for(decoded_data, count)
                # Empty FortID{} is merely a tautological framing fixture, not
                # a recovered challenge flag. Require at least one body byte.
                if payload and count > 8:
                    print("FLAG-CANDIDATE", name, mask, count, erasure_n,
                          repr(payload), flush=True)
                    return
                body_bits = "".join(f"{x:08b}" for x in decoded_data)
                body = bytes(int(body_bits[i:i + 8], 2)
                             for i in range(12, 12 + count * 8, 8))
                print("FRAMED-DATA", name, mask, count, erasure_n,
                      repr(body), decoded_data.hex(), flush=True)
                tried_counts += 1
            print("finished", name, mask, "framing-compatible counts", tried_counts,
                  flush=True)
    print("NO-FLAG-CANDIDATE", flush=True)


if __name__ == "__main__":
    main()